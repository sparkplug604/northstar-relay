import assert from 'node:assert/strict';
import { randomBytes, randomUUID } from 'node:crypto';
import { after, before, describe, it } from 'node:test';
import { Pool } from 'pg';
import { Secret, TOTP } from 'otpauth';
import type { FastifyInstance } from 'fastify';
import { buildRelayApp } from '../apps/api/src/relay/app.js';
import { migrateRelay, RelayPostgresStore } from '../packages/relay-storage-postgres/src/index.js';

const sourceUrl = process.env.RELAY_TEST_DATABASE_URL;
describe('Relay authenticated operator API with PostgreSQL', { skip: !sourceUrl }, () => {
  const origin = 'http://127.0.0.1:4310';
  const dbName = `relay_api_${randomBytes(6).toString('hex')}`;
  const connectionUrl = sourceUrl ? new URL(sourceUrl) : new URL('postgres://localhost/unused'); connectionUrl.pathname = `/${dbName}`;
  const pool = new Pool({ connectionString: connectionUrl.toString() });
  const store = new RelayPostgresStore(pool);
  let app: FastifyInstance; let cookie = ''; let csrf = ''; let branchId = ''; let personId = ''; let tenantId = ''; let recoveryCode = '';
  const email = `${randomUUID()}@example.invalid`; const password = 'a-long-test-password-123';
  const headers = () => ({ origin, cookie, 'x-csrf-token': csrf });
  before(async () => {
    const admin = new Pool({ connectionString: sourceUrl, max: 1 });
    await admin.query(`CREATE DATABASE "${dbName}"`); await admin.end();
    await migrateRelay(pool);
    app = await buildRelayApp({ store, publicOrigin: origin, secureCookies: false, setupToken: 'only-for-this-test-setup', authEncryptionKey: randomBytes(32).toString('base64') });
  });
  after(async () => { await app?.close(); await pool.end(); });
  it('rejects spoofed demo identity and requires first-admin MFA before operator access', async () => {
    const unauthenticated = await app.inject({ method: 'GET', url: '/api/relay/v1/work-orders', headers: { 'x-demo-user': 'admin-sam' } });
    assert.equal(unauthenticated.statusCode, 401);
    const setup = await app.inject({ method: 'POST', url: '/api/relay/v1/auth/setup', headers: { origin }, payload: { setupToken: 'only-for-this-test-setup', organizationName: 'Relay API test', branchName: 'Test branch', timezone: 'America/Vancouver', displayName: 'Test admin', email, password } });
    assert.equal(setup.statusCode, 200, setup.body); assert.equal(setup.json().mfaRequired, true);
    cookie = String(setup.headers['set-cookie']).split(';')[0]!; csrf = setup.json().csrfToken;
    assert.equal((await app.inject({ method: 'GET', url: '/api/relay/v1/session', headers: headers() })).statusCode, 401);
    const enrollment = await app.inject({ method: 'POST', url: '/api/relay/v1/auth/mfa/enroll', headers: headers() });
    assert.equal(enrollment.statusCode, 200, enrollment.body);
    const code = new TOTP({ secret: Secret.fromBase32(enrollment.json().secret) }).generate();
    const confirmed = await app.inject({ method: 'POST', url: '/api/relay/v1/auth/mfa/confirm', headers: headers(), payload: { totpCode: code } });
    assert.equal(confirmed.statusCode, 200, confirmed.body); assert.equal(confirmed.json().recoveryCodes.length, 8);
    recoveryCode = confirmed.json().recoveryCodes[0];
    const oldCookie = cookie; cookie = String(confirmed.headers['set-cookie']).split(';')[0]!; csrf = confirmed.json().csrfToken;
    assert.notEqual(cookie, oldCookie);
    const session = await app.inject({ method: 'GET', url: '/api/relay/v1/session', headers: headers() });
    assert.equal(session.statusCode, 200, session.body); branchId = session.json().user.branchId; personId = session.json().user.id; tenantId = session.json().organization.id;
  });
  it('requires same-origin CSRF tokens on authenticated mutations', async () => {
    const noCsrf = await app.inject({ method: 'PUT', url: '/api/relay/v1/settings', headers: { origin, cookie }, payload: {} });
    assert.equal(noCsrf.statusCode, 403);
    const wrongOrigin = await app.inject({ method: 'PUT', url: '/api/relay/v1/settings', headers: { ...headers(), origin: 'https://attacker.invalid' }, payload: {} });
    assert.equal(wrongOrigin.statusCode, 403);
    const configured = await app.inject({ method: 'PUT', url: '/api/relay/v1/settings', headers: headers(), payload: { branchId, recipientIds: [personId], intervalSeconds: 60, channels: ['voice'] } });
    assert.equal(configured.statusCode, 200, configured.body);
  });
  it('persists a manually entered work order, idempotent replay, and ownership', async () => {
    const input = { branchId, externalId: randomUUID(), customerReference: 'Test supermarket', priority: 'Emergency', dueAt: new Date(Date.now() + 600000).toISOString(), note: 'Walk-in freezer' };
    const key = randomUUID();
    const created = await app.inject({ method: 'POST', url: '/api/relay/v1/work-orders', headers: { ...headers(), 'idempotency-key': key }, payload: input });
    assert.equal(created.statusCode, 201, created.body);
    const replay = await app.inject({ method: 'POST', url: '/api/relay/v1/work-orders', headers: { ...headers(), 'idempotency-key': key }, payload: input });
    assert.deepEqual(replay.json(), created.json());
    const commitment = created.json().commitment;
    await store.applyCommand({ type: 'activate_commitment', commandId: randomUUID(), tenantId, commitmentId: commitment.commitmentId, actorId: 'worker', actorRole: 'system', occurredAt: await store.now(), correlationId: randomUUID(), expectedVersion: commitment.version, expectedDueAt: commitment.dueAt, expectedActivatesAt: commitment.activatesAt });
    const ownership = await app.inject({ method: 'POST', url: `/api/relay/v1/work-orders/${commitment.commitmentId}/actions`, headers: { ...headers(), 'idempotency-key': randomUUID() }, payload: { action: 'acknowledge', recipientId: personId } });
    assert.equal(ownership.statusCode, 200, ownership.body); assert.equal(ownership.json().commitment.ownerRecipientId, personId);
    const queue = await app.inject({ method: 'GET', url: '/api/relay/v1/work-orders', headers: headers() });
    assert.equal(queue.json().items.length, 1); assert.equal(queue.json().items[0].note, input.note);
    const detail = await app.inject({ method: 'GET', url: `/api/relay/v1/work-orders/${commitment.commitmentId}`, headers: headers() });
    assert.ok(detail.json().events.some((event: { eventType: string }) => event.eventType === 'commitment_acknowledged'));
  });
  it('starts newly entered phone contacts unverified and invalidates verification when changed', async () => {
    const updated = await app.inject({ method: 'PATCH', url: `/api/relay/v1/people/${personId}`, headers: headers(), payload: { phone: '+16045550199' } }); assert.equal(updated.statusCode, 200);
    const people = await app.inject({ method: 'GET', url: '/api/relay/v1/people', headers: headers() });
    assert.equal(people.json().items[0].phoneVerified, false);
  });
  it('versions dated on-call overrides and freezes the resolved recipients on each new work order', async () => {
    const createdPerson = await app.inject({ method: 'POST', url: '/api/relay/v1/people', headers: headers(), payload: { displayName: 'Holiday backup', email: `${randomUUID()}@example.invalid`, password, role: 'on_call_responder', branchId } });
    assert.equal(createdPerson.statusCode, 201, createdPerson.body);
    const backupId = createdPerson.json().id;
    const original = await app.inject({ method: 'GET', url: '/api/relay/v1/work-orders', headers: headers() });
    const originalCommitment = original.json().items[0].commitment;
    const schedule = await app.inject({ method: 'GET', url: `/api/relay/v1/schedules?branchId=${branchId}`, headers: headers() });
    const version = schedule.json().version;
    const override = { startsAt: new Date(Date.now() - 60000).toISOString(), endsAt: new Date(Date.now() + 3600000).toISOString(), recipientIds: [backupId], reason: 'Covering this shift' };
    const saved = await app.inject({ method: 'PUT', url: '/api/relay/v1/schedules', headers: headers(), payload: { branchId, expectedVersion: version, overrides: [override] } });
    assert.equal(saved.statusCode, 200, saved.body); assert.equal(saved.json().version, version + 1);
    const stale = await app.inject({ method: 'PUT', url: '/api/relay/v1/schedules', headers: headers(), payload: { branchId, expectedVersion: version, overrides: [] } });
    assert.equal(stale.statusCode, 409);
    const overlap = await app.inject({ method: 'PUT', url: '/api/relay/v1/schedules', headers: headers(), payload: { branchId, expectedVersion: version + 1, overrides: [override, override] } });
    assert.equal(overlap.statusCode, 422);
    const routed = await app.inject({ method: 'POST', url: '/api/relay/v1/work-orders', headers: { ...headers(), 'idempotency-key': randomUUID() }, payload: { branchId, externalId: randomUUID(), customerReference: 'Backup shift store', priority: 'P1', dueAt: new Date(Date.now() + 600000).toISOString() } });
    assert.equal(routed.statusCode, 201, routed.body);
    assert.equal(routed.json().commitment.policy.version, version + 1);
    assert.equal(routed.json().commitment.recipients[0].personId, backupId);
    assert.match(routed.json().commitment.policy.name, /override:/);
    const existing = await store.getCommitment(tenantId, originalCommitment.commitmentId);
    assert.equal(existing?.policy.version, originalCommitment.policy.version);
    assert.equal(existing?.recipients[0]?.personId, personId);
  });
  it('restricts responders to their current branch and does not trust submitted actor identities', async () => {
    const otherBranch = randomUUID();
    await pool.query('INSERT INTO relay.branches(tenant_id,id,name,timezone) VALUES($1,$2,$3,$4)', [tenantId, otherBranch, 'Another branch', 'America/Toronto']);
    const responderEmail = `${randomUUID()}@example.invalid`;
    const created = await app.inject({ method: 'POST', url: '/api/relay/v1/people', headers: headers(), payload: { displayName: 'Other branch responder', email: responderEmail, password, role: 'on_call_responder', branchId: otherBranch } });
    assert.equal(created.statusCode, 201, created.body);
    const login = await app.inject({ method: 'POST', url: '/api/relay/v1/auth/login', headers: { origin }, payload: { email: responderEmail, password } });
    assert.equal(login.statusCode, 200); assert.equal(login.json().mfaRequired, false);
    const responderHeaders = { origin, cookie: String(login.headers['set-cookie']).split(';')[0]!, 'x-csrf-token': login.json().csrfToken };
    const queue = await app.inject({ method: 'GET', url: '/api/relay/v1/work-orders', headers: responderHeaders });
    assert.equal(queue.json().items.length, 0);
    const adminQueue = await app.inject({ method: 'GET', url: '/api/relay/v1/work-orders', headers: headers() });
    const knownId = adminQueue.json().items[0].commitment.commitmentId;
    const detail = await app.inject({ method: 'GET', url: `/api/relay/v1/work-orders/${knownId}`, headers: responderHeaders });
    assert.equal(detail.statusCode, 403);
    const settings = await app.inject({ method: 'GET', url: `/api/relay/v1/settings?branchId=${branchId}`, headers: responderHeaders });
    assert.equal(settings.statusCode, 403);
    const impersonate = await app.inject({ method: 'POST', url: '/api/relay/v1/people', headers: { ...responderHeaders, 'x-demo-user': personId }, payload: {} });
    assert.equal(impersonate.statusCode, 403);
  });
  it('consumes an MFA recovery code once and revokes previous sessions', async () => {
    const previousCookie = cookie;
    const login = await app.inject({ method: 'POST', url: '/api/relay/v1/auth/login', headers: { origin }, payload: { email, password } });
    const pendingHeaders = { origin, cookie: String(login.headers['set-cookie']).split(';')[0]!, 'x-csrf-token': login.json().csrfToken };
    const recovered = await app.inject({ method: 'POST', url: '/api/relay/v1/auth/mfa/confirm', headers: pendingHeaders, payload: { totpCode: recoveryCode } });
    assert.equal(recovered.statusCode, 200, recovered.body);
    cookie = String(recovered.headers['set-cookie']).split(';')[0]!; csrf = recovered.json().csrfToken;
    assert.equal((await app.inject({ method: 'GET', url: '/api/relay/v1/session', headers: { cookie: previousCookie } })).statusCode, 401);
    const repeatLogin = await app.inject({ method: 'POST', url: '/api/relay/v1/auth/login', headers: { origin }, payload: { email, password } });
    const repeat = await app.inject({ method: 'POST', url: '/api/relay/v1/auth/mfa/confirm', headers: { origin, cookie: String(repeatLogin.headers['set-cookie']).split(';')[0]!, 'x-csrf-token': repeatLogin.json().csrfToken }, payload: { totpCode: recoveryCode } });
    assert.equal(repeat.statusCode, 401);
  });
  it('revokes the session on logout', async () => {
    const logout = await app.inject({ method: 'POST', url: '/api/relay/v1/auth/logout', headers: headers() });
    assert.equal(logout.statusCode, 204);
    assert.equal((await app.inject({ method: 'GET', url: '/api/relay/v1/session', headers: headers() })).statusCode, 401);
  });
});
